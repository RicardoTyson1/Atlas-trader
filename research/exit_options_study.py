"""Exit options + evening window study on the 5 live strategies (pre-registered 2026-11-13, Ricardo).

Question: can the win rate go up (Ricardo's goal ~68%) without losing money, and does the new
evening window (20:00-24:00 NY) make money?

Entries: the 5 live strategies with their live settings, generated by the normal backtest engine.
Windows: "08-11" (08:00-11:00), "20-24" (20:00-24:00), "both".
Exits compared on the SAME entries (each trade replayed bar by bar on the strategy's own candles,
stop checked before target inside a bar, exactly like the engine):
  base        : the live exits (trailing stops etc.), as the engine ran them.
  tp0.5 / tp1 : option 2 - fixed take-profit at 0.5R / 1R, stop stays at the initial stop, no trailing.
                If neither is hit before the live exit (session end, SuperTrend flip, time exit),
                the trade closes where the live one did.
  half1_be    : option 3 - close half at +1R, move the rest's stop to breakeven, the rest then
                follows the live exit (or is stopped at breakeven first).
Costs: real spread + slippage on every fill and $7/lot per side, all in R. "Win" = net R > 0.
Data: GatesFX XAUUSD.R 5m 2023-03 -> 2026-11 (1m 13 months for the 1m reversal), halves A/B at
the date midpoint.
PASS for an exit option: total R >= the live exits' total R in BOTH halves (it must not cost money).
PASS for a window: expectancy > 0 in both halves and >= 100 trades (same bar as every study).

Run in /opt/atlas-research:
  PYTHONPATH=. nice -n 19 python research/exit_options_study.py data/raw/XAUUSD.R_5m.csv data/raw/XAUUSD.R_1m.csv
"""
from __future__ import annotations

import copy
import sys
from datetime import time
from multiprocessing import Pool

import numpy as np
import pandas as pd

from atlas_trader.backtest import run_backtest
from atlas_trader.config import load_config
from atlas_trader.data import load_csv, resample
from atlas_trader.strategies import build_strategy

SYM = "XAUUSD.R"
WINDOWS = {"08-11": "08:00-11:00", "20-24": "20:00-24:00", "both": "08:00-11:00,20:00-24:00"}
# (label, model, timeframe, data, live params without hours)
MODELS = [
    ("smc_ob", "smc_ob", "5m", "5m", {"sweep_bars": 24, "reward_risk": 0.0}),
    ("st_confluence", "st_confluence", "15m", "5m", {"st_mult": 3.0, "vol_mult": 0.0}),
    ("momentum_rsi", "momentum_rsi", "5m", "5m",
     {"disp_atr": 1.0, "trend_filter": True, "trail_start_r": 1.0, "trail_buf_atr": 0.3, "spike_atr": 2.0,
      "max_candle_atr": 2.5, "max_run_atr": 3.0, "run_bars": 12}),
    ("reversal_1m", "reversal_trail", "1m", "1m",
     {"move_atr": 5.0, "rsi_level": 25, "target": "half_move", "spike_atr": 0.0}),
    ("sym_triangle", "chart_patterns", "5m", "5m", {"patterns": "symmetrical_triangle"}),
]
EXITS = ["base", "tp0.5", "tp1", "half1_be"]
DATA: dict = {}


def research_cfg():
    cfg = load_config("config/default.yaml")
    cfg.prop.daily_loss_pct = cfg.prop.max_drawdown_pct = 1e6
    cfg.prop.profit_target_pct = 1e9
    cfg.risk.max_consecutive_losses = 10**6
    cfg.risk.max_trades_per_day = 10**6
    cfg.risk.max_lots = 1e12
    cfg.risk.max_room_fraction_per_trade = 1.0
    cfg.risk.cooldown_after_loss_minutes = 0
    cfg.news.events = []
    cfg.session.trade_start, cfg.session.last_entry = time(0, 0), time(23, 59)
    cfg.session.overnight = True        # live bot holds past midnight (evening entries)
    inst = copy.deepcopy(cfg.instrument(SYM))
    inst.min_lot = inst.lot_step = 1e-9
    return cfg, inst


def replay(df, t, inst, mode) -> float:
    """Net R of one trade under an exit option."""
    o, h, l = df["open"].to_numpy(float), df["high"].to_numpy(float), df["low"].to_numpy(float)
    i0 = df.index.get_loc(t.entry_time)
    j = df.index.get_loc(t.exit_time)
    side, entry, stop0 = int(t.side), float(t.entry), float(t.init_stop)
    risk = abs(entry - stop0)
    half = inst.spread_points / 2 + inst.slippage_points
    comm_r = 2 * inst.commission_per_lot / (risk * inst.value_per_point)
    base_fill = float(t.exit)                          # already includes exit costs

    def r_of(fill):
        return side * (fill - entry) / risk

    if mode == "base":
        return r_of(base_fill) - comm_r
    if mode.startswith("tp"):
        k = float(mode[2:])
        tgt = entry + side * k * risk
        for i in range(i0, j + 1):
            if side * (o[i] - stop0) <= 0:
                return r_of(o[i] - side * half) - comm_r
            if (l[i] <= stop0) if side == 1 else (h[i] >= stop0):
                return r_of(stop0 - side * half) - comm_r
            if side * (o[i] - tgt) >= 0:
                return r_of(o[i] - side * half) - comm_r
            if (h[i] >= tgt) if side == 1 else (l[i] <= tgt):
                return r_of(tgt - side * half) - comm_r
        return r_of(base_fill) - comm_r
    # half1_be: half at +1R, rest stop -> entry, rest otherwise follows the live exit
    one = entry + side * risk
    hit = None
    for i in range(i0, j + 1):
        if (l[i] <= stop0) if side == 1 else (h[i] >= stop0):
            if hit is None:
                return r_of(base_fill) - comm_r       # stopped before +1R: same as live
        if hit is None and ((h[i] >= one) if side == 1 else (l[i] <= one)):
            hit = i
            continue
        if hit is not None and ((l[i] <= entry) if side == 1 else (h[i] >= entry)):
            if i < j:
                return 0.5 * r_of(one - side * half) + 0.5 * r_of(entry - side * half) - comm_r
    if hit is None:
        return r_of(base_fill) - comm_r
    return 0.5 * r_of(one - side * half) + 0.5 * r_of(base_fill) - comm_r


def run(job):
    label, model, tf, data, params, wk, part = job
    cfg, inst = research_cfg()
    df = DATA[(data, tf, part)]
    p = {**params, "hours": WINDOWS[wk]}
    t = run_backtest(df, build_strategy(model, cfg.session, p), inst, cfg).trades
    out = {e: [] for e in EXITS}
    if len(t):
        for tr in t.itertuples():
            for e in EXITS:
                out[e].append(replay(df, tr, inst, e))
    print(f"done {label} {wk} {part}: {len(t)} trades", flush=True)
    return label, wk, part, {e: np.array(v) for e, v in out.items()}


def main(path5, path1):
    for key, path in (("5m", path5), ("1m", path1)):
        base = load_csv(path)
        mid = base.index[0] + (base.index[-1] - base.index[0]) / 2
        for part, d in (("A", base[base.index < mid]), ("B", base[base.index >= mid])):
            for tf in {m[2] for m in MODELS if m[3] == key}:
                DATA[(key, tf, part)] = d if tf == key else resample(d, tf)
    jobs = [(*m, wk, part) for m in MODELS for wk in WINDOWS for part in ("A", "B")]
    with Pool() as pool:
        res = pool.map(run, jobs, chunksize=1)
    tab = {}
    for label, wk, part, r in res:
        tab.setdefault((label, wk), {})[part] = r
    rows = []
    for (label, wk), parts in tab.items():
        for e in EXITS:
            a, b = parts["A"][e], parts["B"][e]
            r = np.concatenate([a, b])
            rows.append({"model": label, "window": wk, "exit": e, "n": len(r),
                         "win%": round(100 * (r > 0).mean(), 1) if len(r) else 0.0,
                         "expR": round(r.mean(), 3) if len(r) else 0.0,
                         "totR": round(r.sum(), 1), "A_totR": round(a.sum(), 1), "B_totR": round(b.sum(), 1)})
    # all 5 together, per window and exit
    for wk in WINDOWS:
        for e in EXITS:
            a = np.concatenate([tab[(m[0], wk)]["A"][e] for m in MODELS])
            b = np.concatenate([tab[(m[0], wk)]["B"][e] for m in MODELS])
            r = np.concatenate([a, b])
            rows.append({"model": "ALL5", "window": wk, "exit": e, "n": len(r),
                         "win%": round(100 * (r > 0).mean(), 1), "expR": round(r.mean(), 3),
                         "totR": round(r.sum(), 1), "A_totR": round(a.sum(), 1), "B_totR": round(b.sum(), 1)})
    t = pd.DataFrame(rows)
    base = t[t.exit == "base"].set_index(["model", "window"])
    t["exit_PASS"] = [
        r.exit != "base" and r.A_totR >= base.loc[(r.model, r.window), "A_totR"]
        and r.B_totR >= base.loc[(r.model, r.window), "B_totR"] for r in t.itertuples()]
    t["window_PASS"] = (t.A_totR > 0) & (t.B_totR > 0) & (t.n >= 100)
    t.to_csv("research/exit_options_results.csv", index=False)
    pd.set_option("display.width", 200)
    print(t.to_string(index=False))


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "data/raw/XAUUSD.R_5m.csv",
         sys.argv[2] if len(sys.argv) > 2 else "data/raw/XAUUSD.R_1m.csv")
